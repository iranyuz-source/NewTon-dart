  function translateString(s) {
    if (!s || !/[A-Za-z]/.test(s)) return s;
    const trimmed = s.trim();
    if (P[trimmed]) {
      const lead = s.match(/^\s*/)?.[0] || '';
      const tail = s.match(/\s*$/)?.[0] || '';
      return lead + P[trimmed] + tail;
    }
    let out = s;
    for (const [re, value] of replacements) out = out.replace(re, value);
    return out;
  }

  function translateNode(node) {
    if (node.nodeType !== Node.TEXT_NODE) return;
    const parent = node.parentElement;
    if (!parent || /^(SCRIPT|STYLE|CODE|PRE|NOSCRIPT|TEXTAREA)$/i.test(parent.tagName)) return;
    const next = translateString(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
  }

  function translateElement(el) {
    if (!el || el.nodeType !== Node.ELEMENT_NODE) return;
    const skip = /^(SCRIPT|STYLE|CODE|PRE|NOSCRIPT)$/i.test(el.tagName);
    if (!skip) {
      el.childNodes.forEach(translateNode);
      ['placeholder','title','aria-label','aria-description'].forEach(attr => {
        if (el.hasAttribute(attr)) {
          const old = el.getAttribute(attr);
          const next = translateString(old);
          if (next !== old) el.setAttribute(attr, next);
        }
      });
    }
  }

  function translate(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) translateNode(root);
    else {
      translateElement(root);
      root.querySelectorAll('*').forEach(translateElement);
    }
    if (document.title) document.title = translateString(document.title);
    document.documentElement.lang = 'fa';
    document.documentElement.dir = 'rtl';
  }

