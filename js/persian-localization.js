  const nativeConfirm = window.confirm.bind(window);
  window.confirm = msg => nativeConfirm(translateString(String(msg)));

  function start() {
    installStyle();
    translate(document.documentElement);
    const observer = new MutationObserver(mutations => {
      for (const m of mutations) {
        if (m.type === 'characterData') translateNode(m.target);
        if (m.type === 'childList') m.addedNodes.forEach(n => {
          if (n.nodeType === Node.ELEMENT_NODE || n.nodeType === Node.TEXT_NODE) translate(n);
        });
      }
    });
    observer.observe(document.body, {subtree:true, childList:true, characterData:true});
    window.NEWTON_PERSIAN = { translate, translateString, dictionary: P };
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start);
  else start();
